/**
 * The schema version, as one number with two readers.
 *
 * `@Database(version = …)` and Story 5.1's exported `schemaVersion` are the same fact: the shape
 * of the data. Written as two literals they would agree today and drift the first time a story
 * bumped the database and forgot the other — and a backup whose `schemaVersion` understates its
 * own shape is a file Story 5.2 would *accept* and then mis-restore, which is the one failure
 * NFR-3 exists to prevent.
 *
 * Top-level and `const` because an annotation argument has to be a compile-time constant, and
 * because a reader who needs the number should find it by grepping the version rather than by
 * opening this file and hoping.
 */
const val SCHEMA_VERSION = 9

/**
 * The app's Room database.
 *
 * Five entities as of Story 3.1: `VEHICLE`, `RENTER`, `CONTRACT` — the real
 * record, renter and frozen daily rate and all, rather than the three placeholder
 * columns Story 2.2 shipped to make the vehicle-delete refusal reachable —
 * `SERVICE_EXCEPTION`, the days a contract was *not* charged, and
 * `BUSINESS_ACCOUNT`, the banks transfers arrive at.
 *
 * ## Why the version moves inside Epic 2
 *
 * This KDoc used to promise version `1` for the life of Epic 2, on the reasoning
 * that "there is no earlier version to migrate from". Story 2.4 makes that
 * reasoning false: v1 exists, as built by 2.2 and 2.3, and any device that
 * already ran them holds that schema on disk.
 *
 * Leaving the version at `1` while adding an entity would make Room's stored
 * identity hash disagree with the compiled schema, and it throws on open rather
 * than degrading. So the rule is now the general one: **bump the version and add
 * a `Migration` whenever the schema changes.**
 *
 * ## Why `fallbackToDestructiveMigration` stays unused
 *
 * Because the KDoc's own warning is right: it would make dropping the owner's
 * fleet — and now their renters and their contracts — one line away, and dropping
 * the owner's data is not a direction to be wrong in. A missing migration fails
 * loudly at open; the fallback fails quietly by deleting the fleet, which is
 * precisely the "disappears and looks like a fresh account" outcome the epic
 * context forbids.
 */
@Database(
    entities = [
        VehicleEntity::class,
        ContractEntity::class,
        RenterEntity::class,
        ServiceExceptionEntity::class,
        BusinessAccountEntity::class,
        PaymentEntity::class,
        AllocationEntity::class,
        SettingEntity::class,
    ],
    version = SCHEMA_VERSION,
    exportSchema = false,
)
@TypeConverters(Converters::class)
abstract class KlinikDatabase : RoomDatabase() {

    abstract fun vehicleDao(): VehicleDao

    abstract fun renterDao(): RenterDao

    abstract fun contractDao(): ContractDao

    abstract fun serviceExceptionDao(): ServiceExceptionDao

    abstract fun businessAccountDao(): BusinessAccountDao

    abstract fun paymentDao(): PaymentDao

    abstract fun allocationDao(): AllocationDao

    abstract fun settingDao(): SettingDao

    companion object {
        private const val NAME = "klinik.db"

        /**
         * v1 -> v2: adds `RENTER`. The first real migration in this app.
         *
         * The statements below are what Room expects for [RenterEntity], written
         * out rather than derived:
         *
         *  - `bankAccount` is the only nullable column, so it is the only one
         *    declared without `NOT NULL`
         *  - no column is renamed with `@ColumnInfo`, so every column name below
         *    is the Kotlin property name verbatim
         *  - `id TEXT NOT NULL` is the primary key — Room emits a `uuid`-typed
         *    domain id as `TEXT`, and the `id` value is generated by
         *    `RenterRepository`, not by the database
         *  - `bankAccount` is declared `TEXT DEFAULT NULL`, not bare `TEXT`. That
         *    is not decoration: `RenterEntity` carries
         *    `@ColumnInfo(defaultValue = "NULL")`, so Room's *compiled* schema
         *    records a default of `NULL` for that column, and Room compares the
         *    recorded defaults when it validates a migrated database. A bare
         *    `TEXT` produces the same nullability but records the default as
         *    undefined, and the migration is refused wholesale with "Migration
         *    didn't properly handle: renter"
         *  - the `UNIQUE` index is created separately under the name Room derives
         *    from `Index(value = ["name"], unique = true)` — `index_renter_name`
         *
         * No `--` comments appear inside these statements. A SQL line comment
         * inside a Kotlin raw string reaches SQLite verbatim and swallows the rest
         * of the statement, which surfaces as a bare `near "/": syntax error`
         * with no line of this file named in it.
         *
         * Room validates the resulting schema against the compiled one when the
         * migration runs, so a column that does not match fails here rather than
         * on the owner's device. `DatabaseMigrationTest` runs this against a
         * real v1 database and asserts the vehicle rows survive.
         */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `renter` (
                        `id` TEXT NOT NULL,
                        `name` TEXT NOT NULL,
                        `phone` TEXT NOT NULL,
                        `bankAccount` TEXT DEFAULT NULL,
                        `emergencyContact` TEXT NOT NULL,
                        PRIMARY KEY (`id`)
                    )
                    """.trimIndent(),
                )
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS `index_renter_name` ON `renter` (`name`)",
                )
            }
        }

        /**
         * v2 -> v3: `CONTRACT` becomes the real record — renter, frozen rate,
         * schedule, and the two columns the one-active rule is enforced by.
         *
         * ## Why this rebuilds the table instead of altering it
         *
         * SQLite cannot add a foreign key with `ALTER TABLE`, so the moment
         * `contract.renterId` must reference `renter` — and it must, exactly as
         * `vehicleId` references `vehicle` — the table has to be recreated.
         *
         * Recreating it also settles the harder question about legacy rows. A v2
         * `contract` row has no renter, no rate and no schedule, so there is no
         * value that could be copied into the new required columns without
         * producing a row that violates the v3 model: a `dailyRate` defaulted to
         * `0` is refused by `ContractEntity.init`, and a `renterId` defaulted to
         * `''` fails the foreign key. No such row can exist in production anyway —
         * nothing in `app/src/main` has ever written a contract, and the test-only
         * seam that could have was declared on `VehicleDao` and is now
         * `ContractDao`'s. The owner's vehicles and renters are untouched, and
         * `DatabaseMigrationTest` asserts they survive.
         *
         * ## What the statements below are, exactly
         *
         * They are what Room expects for [ContractEntity], written out rather than
         * derived:
         *
         *  - column names are the Kotlin property names verbatim — no
         *    `@ColumnInfo(name = …)` rename anywhere
         *  - `startDate`, `restDay` and `endDate` are converted by `Converters`:
         *    dates to ISO `yyyy-MM-dd` TEXT, `restDay` to `DayOfWeek.value`
         *    INTEGER (1 = Monday .. 7 = Sunday)
         *  - `dailyRate` is `INTEGER NOT NULL` — Room emits a `Long` as INTEGER
         *  - every nullable column is declared `DEFAULT NULL`, not bare `TEXT` or
         *    `INTEGER`. That is not decoration: each carries
         *    `@ColumnInfo(defaultValue = "NULL")`, so Room's *compiled* schema
         *    records a default of `NULL`, and Room compares recorded defaults when
         *    it validates a migrated database. A bare declaration produces the same
         *    nullability but records the default as undefined, and the migration is
         *    refused wholesale with "Migration didn't properly handle: contract" —
         *    which is the exact defect `MIGRATION_1_2` shipped with and had to be
         *    fixed for
         *  - both foreign keys are declared, with the same
         *    `ON UPDATE CASCADE ON DELETE RESTRICT` Room derives from the entity's
         *    `ForeignKey` declarations
         *  - the four indexes are created separately under the names Room derives
         *    from the `Index` declarations — `index_contract_vehicleId`,
         *    `index_contract_renterId`, and the two `UNIQUE` ones
         *    `index_contract_activeVehicleId` and `index_contract_activeRenterId`
         *    that are the one-active rule itself
         *
         * No `--` comments appear inside these statements. A SQL line comment
         * inside a Kotlin raw string reaches SQLite verbatim and swallows the rest
         * of the statement, which surfaces as a bare `near "/": syntax error` with
         * no line of this file named in it.
         *
         * Room validates the resulting schema against the compiled one when the
         * migration runs, so a column or an index that does not match fails here
         * rather than on the owner's device. `DatabaseMigrationTest` runs this
         * against a real v2 database and asserts the fleet and the renters survive.
         */
        val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                // ## Why this counts before it drops
                //
                // The argument for dropping rather than migrating the v2 rows is that
                // no v2 row can satisfy the v3 model — see the KDoc above. That
                // argument holds today, but a premise checked only by a grep gate is
                // one refactor away from silently discarding the owner's rows, and
                // losing data quietly is the one failure mode this app's whole design
                // refuses. So the premise is asserted where it is acted on: if any row
                // exists, this throws and the migration fails loudly, with the table
                // untouched. A crash on open is recoverable and visible; a fleet whose
                // contracts vanished is neither.
                val existingRows = db.query("SELECT COUNT(*) FROM `contract`").use { cursor ->
                    if (cursor.moveToFirst()) cursor.getInt(0) else 0
                }
                if (existingRows > 0) {
                    throw IllegalStateException(
                        "MIGRATION_2_3 refuses to drop $existingRows existing contract " +
                            "row(s): the rebuild assumes no v2 row can satisfy the v3 " +
                            "model, and that assumption is now false. Migrate them " +
                            "explicitly instead of dropping the table.",
                    )
                }

                // The old table has no renter, no rate and no schedule, and no row
                // in it can satisfy the v3 model — asserted above, not assumed. The
                // drop also removes the v2 `index_contract_vehicleId`, which is
                // recreated below in its v3 form.
                db.execSQL("DROP TABLE IF EXISTS `contract`")

                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `contract` (
                        `id` TEXT NOT NULL,
                        `renterId` TEXT NOT NULL,
                        `vehicleId` TEXT NOT NULL,
                        `startDate` TEXT NOT NULL,
                        `dailyRate` INTEGER NOT NULL,
                        `restDay` INTEGER DEFAULT NULL,
                        `activeVehicleId` TEXT DEFAULT NULL,
                        `activeRenterId` TEXT DEFAULT NULL,
                        `endDate` TEXT DEFAULT NULL,
                        PRIMARY KEY (`id`),
                        FOREIGN KEY (`renterId`) REFERENCES `renter` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT,
                        FOREIGN KEY (`vehicleId`) REFERENCES `vehicle` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT
                    )
                    """.trimIndent(),
                )

                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_contract_vehicleId` " +
                        "ON `contract` (`vehicleId`)",
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_contract_renterId` " +
                        "ON `contract` (`renterId`)",
                )
                // The one-active rule. Plain UNIQUE indexes over nullable columns
                // rather than partial indexes, because Room cannot express a
                // partial index — see `ContractEntity`'s KDoc. SQLite treats NULLs
                // as distinct in a unique index, so any number of ended contracts
                // may sit here while at most one open one does.
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS `index_contract_activeVehicleId` " +
                        "ON `contract` (`activeVehicleId`)",
                )
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS `index_contract_activeRenterId` " +
                        "ON `contract` (`activeRenterId`)",
                )
            }
        }

        /**
         * v3 -> v4: adds `SERVICE_EXCEPTION`.
         *
         * ## Why this has none of `MIGRATION_2_3`'s "refuse to drop rows" machinery
         *
         * `MIGRATION_2_3` counts `contract` rows and throws if any exist, because it
         * drops and recreates a table, and a premise checked only by a grep gate is
         * one refactor away from discarding the owner's records. This migration runs
         * `CREATE TABLE` and `CREATE UNIQUE INDEX` on a name that does not exist and
         * touches **no existing table**, so there is nothing it can lose and a
         * row-count guard would be theatre. What replaces the guard is the test: the
         * v3 fixture asserts the vehicle, renter *and* contract rows survive the step,
         * and the duplicate provocation proves the index was really created in the
         * migrated file rather than only in the compiled schema. The failure being
         * guarded against is unchanged — a hand-written migration that is subtly
         * wrong — and the *mechanism* for catching it is the fixture, not the
         * migration.
         *
         * ## What the statements below are, exactly
         *
         * They are what Room expects for [ServiceExceptionEntity], written out rather
         * than derived:
         *
         *  - column names are the Kotlin property names verbatim — no
         *    `@ColumnInfo(name = …)` rename anywhere
         *  - `date` is converted by [Converters] to ISO `yyyy-MM-dd` TEXT
         *  - **no column is nullable**, so there is no `DEFAULT NULL` anywhere and
         *    nothing for `@ColumnInfo(defaultValue)` to declare. That is the one
         *    thing this table does differently from the other three, and it is why the
         *    statements are so much shorter than `MIGRATION_2_3`'s — see
         *    [ServiceExceptionEntity]'s KDoc on why no column may become nullable
         *    here without also changing this SQL
         *  - the foreign key is declared with the same
         *    `ON UPDATE CASCADE ON DELETE RESTRICT` Room derives from the entity's
         *    `ForeignKey` declaration
         *  - the unique index is created separately under the name Room derives from
         *    `Index(value = ["contractId", "date"], unique = true)` —
         *    `index_service_exception_contractId_date`. **Room's derived name,
         *    verbatim**: an index created under any other name is refused wholesale at
         *    open, because `SchemaInfoUtilKt.readIndices` compares the index set for
         *    equality. `DatabaseMigrationTest`'s `indexesOf` assertion is what proves
         *    the name is right rather than merely plausible.
         *
         * No `--` comments appear inside these statements. A SQL line comment inside
         * a Kotlin raw string reaches SQLite verbatim and swallows the rest of the
         * statement, which surfaces as a bare `near "/": syntax error` with no line of
         * this file named in it — the exact defect the two migrations above record.
         *
         * Room validates the resulting schema against the compiled one when the
         * migration runs, so a column or an index that does not match fails here
         * rather than on the owner's device. `DatabaseMigrationTest` runs this
         * against a real v3 database and asserts the fleet, the renters and the
         * contracts survive.
         */
        val MIGRATION_3_4 = object : Migration(3, 4) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `service_exception` (
                        `id` TEXT NOT NULL,
                        `contractId` TEXT NOT NULL,
                        `date` TEXT NOT NULL,
                        `reason` TEXT NOT NULL,
                        PRIMARY KEY (`id`),
                        FOREIGN KEY (`contractId`) REFERENCES `contract` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT
                    )
                    """.trimIndent(),
                )
                // The duplicate rule, and the foreign key's index at the same time.
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS " +
                        "`index_service_exception_contractId_date` " +
                        "ON `service_exception` (`contractId`, `date`)",
                )
            }
        }

        /**
         * v4 -> v5: adds `BUSINESS_ACCOUNT`.
         *
         * ## Why this has no index statement, unlike `MIGRATION_3_4`
         *
         * Because the table has no index. `MIGRATION_3_4` creates a `UNIQUE` index because
         * the exception table's duplicate rule *is* that index; an account has no such
         * rule, and the entity declares no `indices`, so there is nothing to create here.
         * That absence is deliberate — two accounts at one bank are legitimate — and
         * `DatabaseMigrationTest`'s `indexesOf` assertion is what keeps it absent.
         *
         * ## Why this has none of `MIGRATION_2_3`'s "refuse to drop rows" machinery
         *
         * `MIGRATION_2_3` counts `contract` rows and throws if any exist, because it drops
         * and recreates a table. This migration runs one `CREATE TABLE` on a name that does
         * not exist and touches **no existing table**, so there is nothing it can lose and a
         * row-count guard would be theatre. What replaces the guard is the test: the v4
         * fixture asserts the vehicle, renter, contract *and* exception rows survive the
         * step.
         *
         * ## What the statement below is, exactly
         *
         * It is what Room expects for [BusinessAccountEntity], written out rather than
         * derived:
         *
         *  - column names are the Kotlin property names verbatim — no `@ColumnInfo(name = …)`
         *    rename anywhere
         *  - **no column is nullable**, so there is no `DEFAULT NULL` anywhere and nothing
         *    for `@ColumnInfo(defaultValue)` to declare. That is the trap this table avoids
         *    rather than handles: Room compares recorded defaults against the compiled
         *    schema and refuses the whole migration when they disagree, so a nullable column
         *    here would force a matching clause below
         *  - **no foreign key**, because nothing references this table yet. `PAYMENT.accountId`
         *    arrives in Story 3.2, and the `ON DELETE RESTRICT` that makes an in-use account
         *    undeletable is added with it — see `BusinessAccountDao`'s KDoc on why the
         *    delete refusal is not shipped before there is a row to refuse against
         *
         * No `--` comments appear inside the statement. A SQL line comment inside a Kotlin
         * raw string reaches SQLite verbatim and swallows the rest of the statement, which
         * surfaces as a bare `near "/": syntax error` with no line of this file named in it
         * — the exact defect the two migrations above record.
         */
