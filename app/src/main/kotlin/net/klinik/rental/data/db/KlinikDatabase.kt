        /**
         * v5 -> v6: adds `PAYMENT`, `ALLOCATION` and `SETTINGS`.
         *
         * ## What is load-bearing in the statements below
         *
         * Three things, each of which fails loudly rather than degrading:
         *
         *  - **`UNIQUE(paymentId, chargeDate)` on `allocation`**, under Room's derived name
         *    `index_allocation_paymentId_chargeDate`. This is a **correctness** constraint, not
         *    an index: without it one deposit could write two rows for the same charge day, and
         *    `Σ allocation == amount` would break in a way no sum of the other rows reveals.
         *    Room compares the index set for equality on open, so a differently-named index
         *    is refused wholesale — `DatabaseMigrationTest`'s `indexesOf` assertion is what
         *    proves the name rather than assuming it.
         *
         *  - **`ON DELETE RESTRICT` on both of `payment`'s foreign keys**, and on
         *    `allocation.paymentId`. A deposit is money the owner took: cancelling it (Story
         *    3.4) is a *delete*, and `CASCADE` here would let a cascade take the payment with
         *    its allocations in either direction. The `payment.accountId` restriction is also
         *    the delete refusal Story 3.1 deferred — a bank account with deposits on it
         *    cannot be deleted.
         *
         *  - **`DEFAULT NULL` on every nullable column.** Room compares recorded column
         *    defaults against the compiled schema and refuses the whole migration when they
         *    disagree, so a `@ColumnInfo(defaultValue = "NULL")` with no matching clause here
         *    is not a cosmetic omission: the database will not open.
         *
         * ## Why `settings` is created empty
         *
         * No `cutoffDay` row is seeded. `SettingDao.findInt` supplies the default on read, so a
         * fresh install records its first deposit against the default cutoff rather than
         * failing because configuration was never written — and "unset" stays distinguishable
         * from "set to 25", which matters the moment Story 5.4 wants to show the owner what
         * the value actually is.
         *
         * No `--` comments appear inside any statement. A SQL line comment inside a Kotlin raw
         * string reaches SQLite verbatim and swallows the rest, which surfaces as a bare
         * `near "/": syntax error` with no line of this file named in it.
         */
        val MIGRATION_5_6 = object : Migration(5, 6) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `payment` (
                        `id` TEXT NOT NULL,
                        `contractId` TEXT NOT NULL,
                        `accountId` TEXT DEFAULT NULL,
                        `date` TEXT NOT NULL,
                        `amount` INTEGER NOT NULL,
                        `method` TEXT NOT NULL,
                        `referenceNo` TEXT DEFAULT NULL,
                        `notes` TEXT DEFAULT NULL,
                        `createdAt` TEXT NOT NULL,
                        PRIMARY KEY (`id`),
                        FOREIGN KEY (`contractId`) REFERENCES `contract` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT,
                        FOREIGN KEY (`accountId`) REFERENCES `business_account` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT
                    )
                    """.trimIndent(),
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_payment_contractId` " +
                        "ON `payment` (`contractId`)",
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_payment_accountId` " +
                        "ON `payment` (`accountId`)",
                )

                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `allocation` (
                        `id` TEXT NOT NULL,
                        `paymentId` TEXT NOT NULL,
                        `contractId` TEXT NOT NULL,
                        `chargeDate` TEXT DEFAULT NULL,
                        `amount` INTEGER NOT NULL,
                        PRIMARY KEY (`id`),
                        FOREIGN KEY (`paymentId`) REFERENCES `payment` (`id`)
                            ON UPDATE CASCADE ON DELETE RESTRICT
                    )
                    """.trimIndent(),
                )
                // The duplicate-day guard, and the arrears query's index. Both are needed;
                // the first is correctness, the second is what keeps the number the app is
                // built around off a table scan. `chargeDate` is the *column* name, so the
                // index Room derives from it is `index_allocation_paymentId_chargeDate` —
                // not the domain value's shorter spelling.
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS `index_allocation_paymentId_chargeDate` " +
                        "ON `allocation` (`paymentId`, `chargeDate`)",
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_allocation_contractId_date` " +
                        "ON `allocation` (`contractId`, `chargeDate`)",
                )

                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `settings` (
                        `key` TEXT NOT NULL,
                        `value` TEXT NOT NULL,
                        PRIMARY KEY (`key`)
                    )
                    """.trimIndent(),
                )
            }
        }

        /**
         * v6 -> v7: adds `payment.status` and `payment.cancelReason` — Story 3.4's
         * cancellation trail.
         *
         * ## Why this is the first `ALTER` here, and why the `DEFAULT` matters
         *
         * Every migration above *created* a table, so none of them had to reason about
         * existing rows. These two columns are added to a table that already holds the
         * owner's deposits, and that is where the default clause stops being decoration:
         *
         *  - `status TEXT NOT NULL DEFAULT 'confirmed'` — without the default, every
         *    existing row reads back `null`, fails the entity's non-null guard, and the
         *    owner loses access to their own history. **SQLite cannot add a `NOT NULL`
         *    column without a default**, so the clause is required by the type, not by
         *    taste.
         *  - `cancelReason TEXT DEFAULT NULL` — a confirmed deposit has no reason, and
         *    `DEFAULT ''` would make "cancelled with no reason" representable, which is
         *    exactly what the epic forbids.
         *
         * ## Why no row is rewritten
         *
         * `ALTER TABLE … ADD COLUMN` is the whole migration. Back-filling every deposit
         * would be a second write path for a value the default already supplies, and the
         * rows it would touch are money records whose `createdAt` and `date` must not move.
         */
        val MIGRATION_6_7 = object : Migration(6, 7) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE `payment` " +
                        "ADD COLUMN `status` TEXT NOT NULL DEFAULT 'confirmed'"
                )
                db.execSQL(
                    "ALTER TABLE `payment` ADD COLUMN `cancelReason` TEXT DEFAULT NULL"
                )
            }
        }

        /**
         * v7 -> v8: adds `contract.settledThroughDate` — Story 3.6's FR-9b marker.
         *
         * ## Why `DEFAULT NULL` is written out rather than left implicit
         *
         * `ContractEntity` declares `@ColumnInfo(defaultValue = "NULL")`, so Room's
         * compiled schema *records* a default of `NULL` for this column, and Room
         * compares recorded defaults when it validates a migrated database. A bare
         * `TEXT` produces the same nullability but records the default as undefined,
         * and the migration is refused wholesale with "Migration didn't properly
         * handle: contract" — the exact defect `MIGRATION_1_2` shipped with.
         *
         * ## Why no row is rewritten
         *
         * The whole migration is the `ALTER`. Every existing contract settles on `null`,
         * which is what "no settlement" means, so there is nothing to back-fill and no
         * reason to touch rows whose dates the owner relies on. The second `ALTER`-only
         * migration after `MIGRATION_6_7`, for the same reason it is the first.
         */
        val MIGRATION_7_8 = object : Migration(7, 8) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE `contract` " +
                        "ADD COLUMN `settledThroughDate` TEXT DEFAULT NULL"
                )
            }
        }

        /**
         * v8 -> v9: adds `renter.avatar` — the emoji the prototype shows on a renter's disc.
         *
         * ## Why `DEFAULT NULL` and no back-fill
         *
         * `null` means "no emoji chosen", which is the truth about every renter already stored:
         * they were recorded before the field existed, and inventing an emoji for them would be
         * this migration deciding something about a person. `KnAvatar` falls back to initials,
         * which is what every renter disc shows today — so an upgraded install looks unchanged
         * until the owner picks one.
         *
         * The explicit `DEFAULT NULL` is written out for the reason `MIGRATION_7_8` records:
         * `RenterEntity` declares `@ColumnInfo(defaultValue = "NULL")`, Room records that default
         * and compares it when validating, and a bare `TEXT` is refused wholesale.
         *
         * ## The cost this bump accepts
         *
         * `BackupJsonReader` refuses a `schemaVersion` that is not the app's, in both directions,
         * so every **v8 backup** becomes unrestorable. That was a deliberate trade: the app has
         * never shipped, so the only v8 file in existence is the generated demo, and teaching the
         * reader to accept older files is a much larger change than one nullable column — a v6
         * file has no `payment.status` at all, so it needs per-version field defaults rather than
         * a range check. Recorded in `deferred-work.md` as the prerequisite for the next bump.
         */
        val MIGRATION_8_9 = object : Migration(8, 9) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE `renter` " +
                        "ADD COLUMN `avatar` TEXT DEFAULT NULL"
                )
            }
        }

        /**
         * The single application-wide instance.
         *
         * `@Volatile` because `onCreate` and the first screen's first read are
         * on different threads, and a database opened twice under `fallback` is
         * the classic way to end up with two in-memory stores that disagree.
         */
        @Volatile
        private var instance: KlinikDatabase? = null

        fun get(context: Context): KlinikDatabase =
            instance ?: synchronized(this) {
                instance ?: build(context.applicationContext).also { instance = it }
            }

        private fun build(context: Context): KlinikDatabase =
            Room.databaseBuilder(context, KlinikDatabase::class.java, NAME)
                // Every schema change ships its migration here. No
                // `fallbackToDestructiveMigration` — see the class KDoc.
                .addMigrations(
                    MIGRATION_1_2,
                    MIGRATION_2_3,
                    MIGRATION_3_4,
                    MIGRATION_4_5,
                    MIGRATION_5_6,
                MIGRATION_6_7,
                MIGRATION_7_8,
                MIGRATION_8_9,
            )
                .build()
    }
