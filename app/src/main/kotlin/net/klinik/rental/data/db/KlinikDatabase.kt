package net.klinik.rental.data.db

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.TypeConverters
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase
import net.klinik.rental.data.db.dao.RenterDao
import net.klinik.rental.data.db.dao.VehicleDao
import net.klinik.rental.data.db.entity.ContractEntity
import net.klinik.rental.data.db.entity.RenterEntity
import net.klinik.rental.data.db.entity.VehicleEntity

/**
 * The app's Room database.
 *
 * Three entities as of Story 2.4: `VEHICLE`, the minimum `CONTRACT` that makes
 * the vehicle-delete refusal enforceable, and `RENTER`.
 *
 * ## Why the version moves inside Epic 2
 *
 * This KDoc used to promise version `1` for the life of Epic 2, on the reasoning
 * that "there is no earlier version to migrate from". Story 2.4 makes that
 * reasoning false: v1 exists, as built by 2.2 and 2.3, and any device that
 * already ran them holds that schema on disk.
 *
 * Leaving the version at `1` while adding an entity would make Room's stored
 * identity hash disagree with the compiled schema, and it throws on open rather
 * than degrading. So the rule is now the general one: **bump the version and add
 * a `Migration` whenever the schema changes.**
 *
 * ## Why `fallbackToDestructiveMigration` stays unused
 *
 * Because the KDoc's own warning is right: it would make dropping the owner's
 * fleet — and now their renters — one line away, and dropping the owner's data is
 * not a direction to be wrong in. A missing migration fails loudly at open; the
 * fallback fails quietly by deleting the fleet, which is precisely the
 * "disappears and looks like a fresh account" outcome the epic context forbids.
 */
@Database(
    entities = [VehicleEntity::class, ContractEntity::class, RenterEntity::class],
    version = 2,
    exportSchema = false,
)
@TypeConverters(Converters::class)
abstract class KlinikDatabase : RoomDatabase() {

    abstract fun vehicleDao(): VehicleDao

    abstract fun renterDao(): RenterDao

    companion object {
        private const val NAME = "klinik.db"

        /**
         * v1 -> v2: adds `RENTER`. The first real migration in this app.
         *
         * The statements below are what Room expects for [RenterEntity], written
         * out rather than derived:
         *
         *  - `bankAccount` is the only nullable column, so it is the only one
         *    declared without `NOT NULL`
         *  - no column is renamed with `@ColumnInfo`, so every column name below
         *    is the Kotlin property name verbatim
         *  - `id TEXT NOT NULL` is the primary key — Room emits a `uuid`-typed
         *    domain id as `TEXT`, and the `id` value is generated by
         *    `RenterRepository`, not by the database
         *  - `bankAccount` is declared `TEXT DEFAULT NULL`, not bare `TEXT`. That
         *    is not decoration: `RenterEntity` carries
         *    `@ColumnInfo(defaultValue = "NULL")`, so Room's *compiled* schema
         *    records a default of `NULL` for that column, and Room compares the
         *    recorded defaults when it validates a migrated database. A bare
         *    `TEXT` produces the same nullability but records the default as
         *    undefined, and the migration is refused wholesale with "Migration
         *    didn't properly handle: renter"
         *  - the `UNIQUE` index is created separately under the name Room derives
         *    from `Index(value = ["name"], unique = true)` — `index_renter_name`
         *
         * No `--` comments appear inside these statements. A SQL line comment
         * inside a Kotlin raw string reaches SQLite verbatim and swallows the rest
         * of the statement, which surfaces as a bare `near "/": syntax error`
         * with no line of this file named in it.
         *
         * Room validates the resulting schema against the compiled one when the
         * migration runs, so a column that does not match fails here rather than
         * on the owner's device. `DatabaseMigrationTest` runs this against a
         * real v1 database and asserts the vehicle rows survive.
         */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `renter` (
                        `id` TEXT NOT NULL,
                        `name` TEXT NOT NULL,
                        `phone` TEXT NOT NULL,
                        `bankAccount` TEXT DEFAULT NULL,
                        `emergencyContact` TEXT NOT NULL,
                        PRIMARY KEY (`id`)
                    )
                    """.trimIndent(),
                )
                db.execSQL(
                    "CREATE UNIQUE INDEX IF NOT EXISTS `index_renter_name` ON `renter` (`name`)",
                )
            }
        }

        /**
         * The single application-wide instance.
         *
         * `@Volatile` because `onCreate` and the first screen's first read are
         * on different threads, and a database opened twice under `fallback` is
         * the classic way to end up with two in-memory stores that disagree.
         */
        @Volatile
        private var instance: KlinikDatabase? = null

        fun get(context: Context): KlinikDatabase =
            instance ?: synchronized(this) {
                instance ?: build(context.applicationContext).also { instance = it }
            }

        private fun build(context: Context): KlinikDatabase =
            Room.databaseBuilder(context, KlinikDatabase::class.java, NAME)
                // Every schema change ships its migration here. No
                // `fallbackToDestructiveMigration` — see the class KDoc.
                .addMigrations(MIGRATION_1_2)
                .build()
    }
}